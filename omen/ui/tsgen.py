"""TypeScript types for the web UI, generated from the Pydantic component models.

    python -m omen schema --ts > web/src/generated/components.ts

Handles the JSON Schema subset Pydantic emits for the flat component models:
objects, arrays, primitives, literals/enums, nullable unions and local $refs.
"""

from __future__ import annotations

from typing import Any

from omen.ui.components import TYPES, UIPayload, VERSION

_PRIMITIVES = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}


def _ts_type(schema: dict[str, Any], defs: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return _literal(schema["const"])
    if "enum" in schema:
        return " | ".join(_literal(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(dict.fromkeys(_ts_type(s, defs) for s in schema[key]))
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(_PRIMITIVES.get(k, "unknown") for k in kind)
    if kind == "array":
        item = _ts_type(schema.get("items", {}), defs)
        return f"({item})[]" if "|" in item else f"{item}[]"
    if kind == "object":
        if "properties" in schema:
            return _object(schema, defs)
        return "Record<string, unknown>"
    return _PRIMITIVES.get(kind, "unknown")


def _literal(value: Any) -> str:
    return f'"{value}"' if isinstance(value, str) else str(value).lower()


def _object(schema: dict[str, Any], defs: dict[str, Any], skip: tuple[str, ...] = ()) -> str:
    required = set(schema.get("required", []))
    lines = []
    for name, prop in schema.get("properties", {}).items():
        if name in skip:
            continue
        optional = "" if name in required else "?"
        lines.append(f"  {name}{optional}: {_ts_type(prop, defs)};")
    return "{\n" + "\n".join(lines) + "\n}"


def _pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def typescript() -> str:
    out = [
        "// Generated by `python -m omen schema --ts` from omen/ui/components.py. Do not edit.",
        f"export const UI_VERSION = {VERSION};",
        "",
    ]
    emitted_defs: set[str] = set()
    names = []
    for kind, model in TYPES.items():
        schema = model.model_json_schema()
        defs = schema.get("$defs", {})
        for def_name, def_schema in defs.items():
            if def_name not in emitted_defs:
                emitted_defs.add(def_name)
                out.append(f"export interface {def_name} {_object(def_schema, defs)}")
                out.append("")
        name = f"{_pascal(kind)}Props"
        names.append((kind, name))
        out.append(f"export interface {name} {_object(schema, defs, skip=('type',))}")
        out.append("")
    out.append("export interface ComponentProps {")
    out += [f'  "{kind}": {name};' for kind, name in names]
    out.append("}")
    out.append("")
    out.append("export type ComponentType = keyof ComponentProps;")
    out.append(f"export const COMPONENT_TYPES: ComponentType[] = [{', '.join(repr(k).replace(chr(39), chr(34)) for k, _ in names)}];")
    out.append("")
    payload = UIPayload.model_json_schema()
    out.append(f"export interface UIPayload {_object(payload, payload.get('$defs', {}))}")
    out.append("")
    return "\n".join(out)
